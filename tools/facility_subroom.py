#!/usr/bin/env python3
"""Facility subroom pieces: place, prove and generate (PROCEDURAL_SUBROOMS_PLAN Phase 4).

The Facility's subroom (PROCEDURAL_FACILITY_SUBROOM) is an 11x9 block map of
black void. Each Facility rolls one of the generator's own full-room pieces
(PFacRoomDescriptors), and every load stamps it, whole and centred, then stamps
the pad block on that piece's designated landing spot and stands the residents
on their designated tiles.

Warp arrival tiles are fixed in ROM, so the map declares a few LANDINGS (one
warp each). This script chooses that set so every piece has one: for each piece
it collects the blocks where the pad may go (plain floor, pad tile in the
piece's main walkable area, and the area stays connected with the pad standing
in it, since stepping on the pad leaves the room), then picks landings greedily
until every piece is covered. Per piece it then picks:
  - the landing (the first covering one, in the order chosen),
  - the Super Nerd's tile, talked to from the tile below (so he faces down),
    nearest the room's centre,
  - the item ball's tile, far from the pad and from him,
each one blocking no path: everything walkable from the pad stays walkable with
both standing there. Pieces are weighted by interior area / 3 (the user prefers
larger rooms; a byte-sized pick list holds the result). A piece with no valid
spot is left out (listed on stderr). The ROM reads the generated files; it checks nothing itself.

    python3 tools/facility_subroom.py           # prove + regenerate the asm
    python3 tools/facility_subroom.py --show    # draw every placement
    python3 tools/facility_subroom.py --check   # prove + compare, no write
"""

from __future__ import annotations

import argparse
import importlib.util
import re
import sys
from collections import deque
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GEN_ASM = ROOT / "custom_functions" / "procedural_facility_gen.asm"
OUT_ASM = ROOT / "data" / "maps" / "facility_subroom_pieces.asm"
OUT_CONST = ROOT / "constants" / "facility_subroom_constants.asm"
MAP_BLK = ROOT / "maps" / "ProceduralFacilitySubroom.blk"

_spec = importlib.util.spec_from_file_location(
    "check_facility_premades", ROOT / "tools" / "check_facility_premades.py")
premades = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(premades)

MAP_W, MAP_H = 11, 9           # blocks; must match map_const PROCEDURAL_FACILITY_SUBROOM
VOID = 0x2E
FLOOR = 0x0E                   # PFAC_FLOOR: the only block a pad may replace
PAD_BLOCK = 0x2F               # floor with the pad in its bottom-right quadrant
MAX_PICKS = 255
MAX_LANDINGS = 16

DESC_RE = re.compile(r"^\s*db (\d+), (\d+), ([A-Z_| ]+?), .*\n\s*dw (PFacTplData\w+)", re.M)
DATA_RE = re.compile(r'^(PFacTplData\w+):\n\s*INCBIN "maps/([^"]+)"', re.M)
GENERATED = "; GENERATED by tools/facility_subroom.py - do not edit. Rerun the tool after\n" \
            "; changing a Facility room piece or the subroom's size.\n"


def load_pieces() -> list[dict]:
    text = GEN_ASM.read_text(encoding="utf-8")
    files = dict(DATA_RE.findall(text))
    pieces = []
    for w, h, _mask, label in DESC_RE.findall(text):
        payload = (ROOT / "maps" / files[label]).read_bytes()
        w, h = int(w), int(h)
        assert len(payload) == w * h, label
        pieces.append({"label": label, "file": files[label], "w": w, "h": h, "payload": payload})
    return pieces


def place(piece: dict) -> tuple[list[list[int]], int, int]:
    w, h = piece["w"], piece["h"]
    x0, y0 = (MAP_W - w) // 2, (MAP_H - h) // 2
    assert x0 >= 1 and y0 >= 1, f"{piece['file']} does not fit the subroom with a void margin"
    grid = [[VOID] * MAP_W for _ in range(MAP_H)]
    for r in range(h):
        for c in range(w):
            grid[y0 + r][x0 + c] = piece["payload"][r * w + c]
    return grid, x0, y0


def walkable_cells(grid, blockset) -> set[tuple[int, int]]:
    cells = set()
    for by, row in enumerate(grid):
        for bx, block in enumerate(row):
            for q, ok in enumerate(premades.block_quadrants(blockset, block)):
                if ok:
                    cells.add((bx * 2 + q % 2, by * 2 + q // 2))
    return cells


def neighbours(t):
    x, y = t
    return ((x + 1, y), (x - 1, y), (x, y + 1), (x, y - 1))


def flood(cells, starts) -> set[tuple[int, int]]:
    seen = {s for s in starts if s in cells}
    todo = deque(seen)
    while todo:
        for n in neighbours(todo.popleft()):
            if n in cells and n not in seen:
                seen.add(n)
                todo.append(n)
    return seen


def pad_tile(block):
    return (2 * block[0] + 1, 2 * block[1] + 1)


def walk_area(grid, pad_block, blockset):
    """The tiles the player can use, arriving on the pad: the pad's component,
    minus the pad itself (stepping back onto it leaves the room)."""
    stamped = [row[:] for row in grid]
    stamped[pad_block[1]][pad_block[0]] = PAD_BLOCK
    cells = walkable_cells(stamped, blockset)
    pad = pad_tile(pad_block)
    assert pad in cells, "the pad tile itself must be walkable"
    return flood(cells, [pad]) - {pad}, cells


def connected_from_pad(walk, pad, taken) -> bool:
    rest = walk - taken
    return bool(rest) and flood(rest, neighbours(pad)) == rest


def pad_spots(piece, grid, x0, y0, blockset) -> list[tuple[int, int]]:
    main = max(_components(walkable_cells(grid, blockset)), key=len)
    spots = []
    for by in range(y0, y0 + piece["h"]):
        for bx in range(x0, x0 + piece["w"]):
            if grid[by][bx] != FLOOR:
                continue
            walk, _ = walk_area(grid, (bx, by), blockset)
            pad = pad_tile((bx, by))
            # Its area must be the room's main one, and stay whole around the pad.
            if pad in main and len(walk) + 1 >= len(main) and connected_from_pad(walk, pad, set()):
                spots.append((bx, by))
    return spots


def _components(cells):
    left, comps = set(cells), []
    while left:
        comp = flood(left, [next(iter(left))])
        comps.append(comp)
        left -= comp
    return comps


def choose_landings(placed, blockset) -> list[tuple[int, int]]:
    uncovered = {i for i in range(len(placed))}
    landings = []
    centre = (MAP_W // 2, MAP_H // 2)
    while uncovered:
        votes = {}
        for i in uncovered:
            for spot in placed[i]["spots"]:
                votes[spot] = votes.get(spot, 0) + 1
        if not votes:
            bad = ", ".join(placed[i]["file"] for i in sorted(uncovered))
            raise SystemExit(f"no pad spot at all in: {bad}")
        # Most pieces covered; then lower in the room, then nearer the centre column.
        best = max(votes, key=lambda s: (votes[s], s[1], -abs(s[0] - centre[0])))
        landings.append(best)
        uncovered = {i for i in uncovered if best not in placed[i]["spots"]}
    if len(landings) > MAX_LANDINGS:
        raise SystemExit(f"{len(landings)} landings exceed {MAX_LANDINGS}")
    return landings


def solve_residents(s, landing_index, landings, blockset) -> None:
    pad_block = landings[landing_index]
    walk, _ = walk_area(s["grid"], pad_block, blockset)
    pad = pad_tile(pad_block)
    hub = (2 * s["x"] + s["w"], 2 * s["y"] + s["h"])          # room centre, in tiles
    nerds = sorted(
        (abs(x - hub[0]) + abs(y - hub[1]), y, x)
        for x, y in walk
        if (x, y + 1) in walk and connected_from_pad(walk, pad, {(x, y)}))
    if not nerds:
        raise SystemExit(f"{s['file']}: no tile for the Super Nerd")
    _, ny, nx = nerds[0]
    nerd, talk = (nx, ny), (nx, ny + 1)
    balls = sorted(
        (-(abs(x - pad[0]) + abs(y - pad[1])), -(abs(x - nx) + abs(y - ny)), y, x)
        for x, y in walk
        if (x, y) != talk and connected_from_pad(walk, pad, {nerd, (x, y)}))
    if not balls:
        raise SystemExit(f"{s['file']}: no tile for the item ball")
    *_, by, bx = balls[0]
    s.update(landing=landing_index, pad=pad, nerd=nerd, ball=(bx, by), walk=walk)


def solve_all(blockset: bytes) -> tuple[list[dict], list[tuple[int, int]]]:
    assert all(premades.block_quadrants(blockset, PAD_BLOCK)), "the pad block must be all floor"
    placed = []
    for piece in load_pieces():
        grid, x0, y0 = place(piece)
        area = (piece["w"] - 2) * (piece["h"] - 2)
        placed.append({**piece, "grid": grid, "x": x0, "y": y0,
                       "spots": pad_spots(piece, grid, x0, y0, blockset),
                       "weight": max(1, area // 3)})
    # A piece with nowhere to put the pad (its only floor is the doorway or
    # the pad would cut its one walkable loop) stays out of the subroom.
    skipped = [s["file"] for s in placed if not s["spots"]]
    placed = [s for s in placed if s["spots"]]
    landings = choose_landings(placed, blockset)
    for s in placed:
        index = next(i for i, spot in enumerate(landings) if spot in s["spots"])
        solve_residents(s, index, landings, blockset)
    return placed, landings, skipped


def draw(s: dict) -> str:
    lines = []
    for ty in range(2 * MAP_H):
        row = ""
        for tx in range(2 * MAP_W):
            t = (tx, ty)
            row += ("N" if t == s["nerd"] else "o" if t == s["ball"] else
                    "P" if t == s["pad"] else "." if t in s["walk"] else "#")
        lines.append(row)
    return "\n".join(lines)


def generate_constants(landings) -> str:
    out = [GENERATED.rstrip("\n"), "",
           f"DEF FACSUB_MAP_W EQU {MAP_W}",
           f"DEF FACSUB_PAD_BLOCK EQU ${PAD_BLOCK:02X}",
           "; Landing spots, in blocks: the subroom's first warps, in this order.",
           f"DEF FACSUB_NUM_LANDINGS EQU {len(landings)}"]
    for i, (bx, by) in enumerate(landings):
        out.append(f"DEF FACSUB_LANDING_{i}_X EQU {bx}")
        out.append(f"DEF FACSUB_LANDING_{i}_Y EQU {by}")
    return "\n".join(out) + "\n"


def generate_table(placed) -> str:
    picks = []
    for i, s in enumerate(placed):
        picks += [i] * s["weight"]
    if len(picks) > MAX_PICKS:
        raise SystemExit(f"{len(picks)} weighted picks exceed {MAX_PICKS}")
    out = [GENERATED.rstrip("\n"), ";",
           "; One row per Facility full-room piece. Row: dw payload (in PFacRoomDescriptors'",
           "; bank); db footprint w, h, top-left block x, y, landing index, Super Nerd tile",
           "; x, y, ball tile x, y. Every row is proven by the tool: the pad reaches the",
           "; whole room, and neither object blocks any path.",
           f"DEF FACSUB_NUM_PIECES EQU {len(placed)}",
           "DEF FACSUB_PIECE_STRIDE EQU 11",
           "",
           "FacSubroomLandings:"]
    out.append("\tFOR n, FACSUB_NUM_LANDINGS")
    out.append("\t\tdb FACSUB_LANDING_{d:n}_X, FACSUB_LANDING_{d:n}_Y")
    out.append("\tENDR")
    out += ["", "FacSubroomPieces:"]
    for s in placed:
        out.append(f"\tdw {s['label']}")
        out.append("\tdb {w}, {h}, {x}, {y}, {l}, {nx}, {ny}, {bx}, {by}".format(
            w=s["w"], h=s["h"], x=s["x"], y=s["y"], l=s["landing"],
            nx=s["nerd"][0], ny=s["nerd"][1], bx=s["ball"][0], by=s["ball"][1]))
        out.append(f"\tASSERT BANK({s['label']}) == BANK(PFacRoomDescriptors)")
    out += ["", "; Weighted by interior area / 3 (larger rooms preferred): a uniform pick from",
            "; this list names a row.", "FacSubroomPicks:", f"\tdb {len(picks)}"]
    for i in range(0, len(picks), 16):
        out.append("\tdb " + ", ".join(str(p) for p in picks[i:i + 16]))
    return "\n".join(out) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--show", action="store_true")
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    if MAP_BLK.read_bytes() != bytes([VOID] * (MAP_W * MAP_H)):
        raise SystemExit(f"{MAP_BLK.name} must be {MAP_W}x{MAP_H} blocks of void (${VOID:02X})")
    placed, landings, skipped = solve_all(premades.BLOCKSET.read_bytes())
    for name in skipped:
        print(f"not used (no pad spot): {name}", file=sys.stderr)
    if args.show:
        print("landings:", landings)
        for s in placed:
            print(f"{s['file']} at ({s['x']},{s['y']}) landing {s['landing']} weight {s['weight']}")
            print(draw(s), end="\n\n")
    outputs = {OUT_CONST: generate_constants(landings), OUT_ASM: generate_table(placed)}
    if args.check:
        stale = [p for p, text in outputs.items() if p.read_text(encoding="utf-8") != text]
        for p in stale:
            print(f"{p.relative_to(ROOT)} is stale: rerun tools/facility_subroom.py")
        return 1 if stale else 0
    if not args.show:
        for p, text in outputs.items():
            p.write_text(text, encoding="utf-8", newline="\n")
    total = sum(s["weight"] for s in placed)
    print(f"{len(placed)} pieces proven, {len(landings)} landings, {total} weighted picks",
          file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
