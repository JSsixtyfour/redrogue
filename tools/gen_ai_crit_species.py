#!/usr/bin/env python3
"""Generate data/battle/ai_crit_species.asm: which species learn a high-crit
move by level-up, and at what level.

The AI guesses the move for a player's unrevealed slot (engine/battle/ai/
ai_accessors.asm, AIGetPlayerMoveN) the way a player who sees a Persian
expects Slash. None of these moves is a TM, so the level-up list is the only
normal source (AI_REVIEW_PLAN_2026-11-12.md, CP3). Sourced from
data/pokemon/evos_moves.asm via tools/learnset_legality.py; a species' OWN list
only (an evolved mon's list restates inherited moves at level 2), and the base
species' list for every form.

    python3 tools/gen_ai_crit_species.py          # rewrite the file
    python3 tools/gen_ai_crit_species.py --check  # fail if it is stale (make audit)
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools"))
sys.path.insert(0, os.path.join(ROOT, "tools", "pyboy_smoke"))
import learnset_legality  # noqa: E402
from pathlib import Path  # noqa: E402
from source_constants import parse_rgbds_constants  # noqa: E402

OUT = os.path.join(ROOT, "data", "battle", "ai_crit_species.asm")
# data/battle/critical_hit_moves.asm
MOVES = ("KARATE_CHOP", "RAZOR_LEAF", "CRABHAMMER", "SLASH")


def high_crit_moves_from_engine():
    text = open(os.path.join(ROOT, "data", "battle", "critical_hit_moves.asm"), encoding="utf-8").read()
    block = re.search(r"^HighCriticalMoves:(.*?)\bdb -1", text, re.M | re.S)
    if not block:
        raise SystemExit("HighCriticalMoves not found in data/battle/critical_hit_moves.asm")
    return tuple(re.findall(r"\b[A-Z][A-Z0-9_]+\b", re.sub(r";.*", "", block.group(1)).replace("db", "")))


def high_crit_moves_in_ai_crit():
    """engine/battle/ai/ai_crit.asm's AIHighCritMoves, the floating section's own
    copy (AI review CP9: its crit lookup prefilter)."""
    text = open(os.path.join(ROOT, "engine", "battle", "ai", "ai_crit.asm"), encoding="utf-8").read()
    block = re.search(r"^AIHighCritMoves:(.*?)\bdb -1", text, re.M | re.S)
    if not block:
        raise SystemExit("AIHighCritMoves not found in engine/battle/ai/ai_crit.asm")
    return tuple(re.findall(r"\b[A-Z][A-Z0-9_]+\b", re.sub(r";.*", "", block.group(1)).replace("db", "")))


def render():
    if sorted(high_crit_moves_from_engine()) != sorted(MOVES):
        raise SystemExit("HighCriticalMoves changed: update MOVES in tools/gen_ai_crit_species.py")
    if sorted(high_crit_moves_in_ai_crit()) != sorted(MOVES):
        raise SystemExit("AIHighCritMoves (ai_crit.asm) differs from HighCriticalMoves: copy it over")
    species = parse_rgbds_constants(Path(ROOT) / "constants" / "pokemon_constants.asm")
    records = learnset_legality._records(os.path.join(ROOT, "data", "pokemon", "evos_moves.asm"), "EvosMoves")
    rows = []
    for name, ident in species.items():
        if name == "NUM_POKEMON_INDEXES" or not ident:
            continue
        rec = records.get(name.replace("_", "").lower())
        if not rec:
            continue
        for move in MOVES:
            if move in rec[1]:
                rows.append((ident, name, move, rec[1][move]))
    rows.sort()
    lines = [
        "; Generated by tools/gen_ai_crit_species.py from the level-up learnsets. Do not",
        "; edit: rerun the script (make audit fails while this file is stale).",
        "; db species, move, learn level. Sorted by species id; 0 ends the table.",
        "AICritSpeciesTable:",
    ]
    for _, name, move, level in rows:
        lines.append("\tdb %s, %s, %d" % (name, move, level))
    lines.append("\tdb 0")
    return "\n".join(lines) + "\n"


def main():
    text = render()
    if "--check" in sys.argv:
        current = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if current.replace("\r\n", "\n") != text:
            print("%s is stale: run python3 tools/gen_ai_crit_species.py" % OUT)
            return 1
        print("ai_crit_species.asm is current")
        return 0
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote", OUT)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
