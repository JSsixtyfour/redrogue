#!/usr/bin/env python3
"""Emit the cave (CAVERN) per-block walkable-quadrant table (PROCEDURAL_SUBROOMS_PLAN Phase 4).

One byte per block in gfx/blocksets/cavern.bst: bit 0 = top-left quadrant
walkable, bit 1 = top-right, bit 2 = bottom-left, bit 3 = bottom-right. A
quadrant is walkable when its collision tile is in Cavern_Coll. The collision
tile is the quadrant's BOTTOM-LEFT tile (block offsets 4, 6, 12, 14): the engine
tests screen tile (8, 9) and its neighbours two tiles away, the bottom-left of
each 16px step (measured in the forest, tools/forest_clearings.py).

Derived, never hand-edited: CaveSubroomPlaceLadders trusts it to prove a ladder
cannot strand anything, so a stale table is a softlock risk.
test_cave_subroom.py fails when it is out of date.

Usage (from the repo root):
    python3 tools/gen_cavern_quad_masks.py           # rewrite the table
    python3 tools/gen_cavern_quad_masks.py --check   # exit 1 if stale
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BLOCKSET = ROOT / "gfx" / "blocksets" / "cavern.bst"
COLLISION = ROOT / "data" / "tilesets" / "collision_tile_ids.asm"
OUT = ROOT / "data" / "tilesets" / "cavern_quad_masks.asm"
QUADRANT_TILE_INDEXES = (4, 6, 12, 14)


def walkable_tiles() -> set[int]:
    text = COLLISION.read_text(encoding="utf-8")
    match = re.search(r"^Cavern_Coll::\s*\n\s*coll_tiles\s+([^\n;]+)", text, re.M)
    if not match:
        raise SystemExit("Cavern_Coll not found in collision_tile_ids.asm")
    return {int(tok.strip().lstrip("$"), 16) for tok in match.group(1).split(",")}


def render() -> str:
    walkable = walkable_tiles()
    blocks = BLOCKSET.read_bytes()
    if len(blocks) % 16:
        raise SystemExit("cavern.bst is not a whole number of 16-byte blocks")
    lines = [
        "; GENERATED by tools/gen_cavern_quad_masks.py from cavern.bst and",
        "; Cavern_Coll. Do not edit by hand; rerun the tool.",
        "; One byte per block: bit 0 TL, 1 TR, 2 BL, 3 BR = that quadrant is walkable.",
        "CavernQuadWalkMasks:",
    ]
    count = len(blocks) // 16
    for start in range(0, count, 8):
        row = []
        for block in range(start, min(start + 8, count)):
            mask = 0
            for bit, index in enumerate(QUADRANT_TILE_INDEXES):
                if blocks[block * 16 + index] in walkable:
                    mask |= 1 << bit
            row.append(f"%{mask:04b}")
        lines.append(f"\tdb {', '.join(row)} ; ${start:02X}")
    lines.append(f"DEF NUM_CAVERN_QUAD_MASKS EQU {count}")
    return "\n".join(lines) + "\n"


def main() -> int:
    text = render()
    if "--check" in sys.argv[1:]:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(f"{OUT.relative_to(ROOT)} is stale: run tools/gen_cavern_quad_masks.py")
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
