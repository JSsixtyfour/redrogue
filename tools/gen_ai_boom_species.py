#!/usr/bin/env python3
"""Generate data/battle/ai_boom_species.asm: which species can ever use
Explosion or Self-Destruct.

The AI's setup gate (engine/battle/ai/ai_setup_gate.asm) treats a foe that can
explode as a threat to set up in front of, the way a player who sees a Golem
knows it may carry Explosion. "Can ever" comes from tools/learnset_legality.py:
level-1 list, level-up learnset, TM/HM list or tutor list of the mon or any
pre-evolution. A species counts if it, or any form of it, qualifies.

    python3 tools/gen_ai_boom_species.py          # rewrite the file
    python3 tools/gen_ai_boom_species.py --check  # fail if it is stale (make audit)
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools"))
sys.path.insert(0, os.path.join(ROOT, "tools", "pyboy_smoke"))
import learnset_legality  # noqa: E402
from pathlib import Path  # noqa: E402
from source_constants import parse_rgbds_constants  # noqa: E402

OUT = os.path.join(ROOT, "data", "battle", "ai_boom_species.asm")
MOVES = ("EXPLOSION", "SELFDESTRUCT")


def render():
    species = parse_rgbds_constants(Path(ROOT) / "constants" / "pokemon_constants.asm")
    count = max(v for k, v in species.items() if k not in ("NUM_POKEMON_INDEXES",))
    # NUM_POKEMON_INDEXES (const_value - 1) is the last species id, i.e. this max.
    boom = set()
    for key, moves in learnset_legality.load().items():
        if any(m in moves for m in MOVES):
            boom.add(key if isinstance(key, str) else key[0])
    missing = sorted(name for name in boom if name not in species)
    if missing:
        raise SystemExit("no species constant for: %s" % ", ".join(missing))
    ids = {species[name]: name for name in boom}
    lines = [
        "; Generated by tools/gen_ai_boom_species.py from the learnsets. Do not edit:",
        "; rerun the script (make audit fails while this file is stale).",
        "; One bit per species id, bit (id & 7) of byte (id >> 3): set when the species,",
        "; or a form of it, can ever learn Explosion or Self-Destruct.",
        "; %d species: %s" % (len(boom), ", ".join(ids[i] for i in sorted(ids))),
        "AIBoomSpeciesBits:",
    ]
    for byte in range(count // 8 + 1):
        bits = 0
        for bit in range(8):
            if byte * 8 + bit in ids:
                bits |= 1 << bit
        lines.append("\tdb %%%s ; $%02X-$%02X" % (format(bits, "08b"), byte * 8, byte * 8 + 7))
    lines.append("\tassert @ - AIBoomSpeciesBits == NUM_POKEMON_INDEXES / 8 + 1, \\")
    lines.append('\t\t"regenerate with tools/gen_ai_boom_species.py"')
    return "\n".join(lines) + "\n"


def main():
    text = render()
    if "--check" in sys.argv:
        current = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if current.replace("\r\n", "\n") != text:
            print("%s is stale: run python3 tools/gen_ai_boom_species.py" % OUT)
            return 1
        print("ai_boom_species.asm is current")
        return 0
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote", OUT)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
