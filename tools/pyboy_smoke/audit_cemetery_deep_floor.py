"""Audit the Cemetery's extra floors over many fresh deep Cemeteries (plan,
Cemetery SPEC C6).

Each Cemetery is entered at round 5 and walked down the whole chain 1, 2, 3, 2b,
3b, 4 by the live stairs (the test module's own `stair`). Checked per Cemetery:
  - the control word is the deep magic and its complement, floor 1 is no b leg;
  - the six stops are the expected floors and legs, in order;
  - 2b's map differs from 2a's and 3b's from 3a's (a fresh floor, not a copy);
  - the Channeler's ordinal (as the lobby rolled it) is in 0-5 and he reads as
    standing on exactly one of the six stops, with his flag shown there only;
  - with the hideout armed on an ordinal 1-5 (rotated through all five), the
    hideout floor is projected onto exactly that stop, never NO_HIDEOUT, and its
    cell is picked once, on that stop's generation;
  - the used-prefab mask only grows, by at most one bit per generated floor.
Reports how many Cemeteries had each Channeler ordinal (all six must occur).

Not checked here: stair-to-stair reachability. A b floor is generated by the
unchanged Cemetery generator, whose march carves that path on every floor; this
audit proves the chain and the projections, not the generator's geometry.

usage (worktree tools/pyboy_smoke): python3 audit_cemetery_deep_floor.py [--cemeteries N]
Exit 1 on any violation.
"""
import argparse
import io
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import test_cemetery_deep_floor as deep  # noqa: E402
from harness import RedRogueHarness  # noqa: E402

NONE = 0xFF
STOPS = [(1, False), (2, False), (3, False), (2, True), (3, True), (4, False)]

ap = argparse.ArgumentParser()
ap.add_argument("--cemeteries", type=int, default=200)
args = ap.parse_args()

h = RedRogueHarness(deep.ROOT, deep.ARTIFACTS)
h.allow_deep_cemetery_floor = True
t = deep.CemeteryDeepFloorTest("test_the_chain_down_and_back")
t.h = h
problems, seen_ordinals, ball_split = [], {}, {}
try:
    h.boot_to_lobby(battle_count=41, encounter_kind=4)
    h.write8("wStageEvent", 0)
    lobby = io.BytesIO()
    h.save_state(lobby)
    for n in range(args.cemeteries):
        h.load_state(lobby)
        h.seed_rng((n & 255, (n >> 8) ^ 0x5A, n * 7 & 255, 1))
        h.preload_and_enter_wild_area(deep.CEM[1], "cemetery")
        h.wait_until(lambda: h.read8("hJoyIgnore") == 0, "settled", 900)
        h.tick(60)
        h.write8("wProcCemWildBudget", 0)
        block = h.read_sram_bytes("sProcCaveStagingBuffer", 5, bank=0)
        if block[0] ^ block[1] != 0xFF or block[0] & deep.MAGIC_MASK != deep.MAGIC:
            problems.append((n, f"not decided deep: {block}"))
            continue
        shadow = block[2]
        if shadow not in (0, deep.GOT_2B, deep.GOT_3B):
            problems.append((n, f"b floors' ball bits {shadow:02x}"))
            continue
        ball_split[shadow] = ball_split.get(shadow, 0) + 1
        chan = block[3]
        if chan > 5:
            problems.append((n, f"Channeler ordinal {chan}"))
            continue
        seen_ordinals[chan] = seen_ordinals.get(chan, 0) + 1
        hide = 1 + n % 5
        h.write_sram_bytes("sStageEventHideoutFloor", [1], bank=0)    # armed
        h.write_sram_bytes("sStageEventHideoutX", [NONE, NONE], bank=0)
        t.poke(hide=hide)
        used = lambda: int.from_bytes(bytes(h.read_sram_bytes("sProcCemeteryUsedPrefabs", 2, bank=0)), "little")
        before, here_chan, here_hide, cell_at = used(), [], [], None
        maps = {}
        for stop, want in enumerate(STOPS):
            if stop:
                t.stair(1, f"cemetery {n}: stop {stop}")
            if t.where() != want:
                problems.append((n, f"stop {stop} is {t.where()}, not {want}"))
                break
            idx = deep.FLOOR[h.read8("hCurMap")] - 1
            if (t.item_got() >> 4) & 3 == idx:
                here_chan.append(stop)
                if t.hidden(f"TOGGLE_CEMETERY_{idx + 1}_CHANNELER"):
                    problems.append((n, f"stop {stop}: the Channeler is here but his flag hides him"))
            elif not t.hidden(f"TOGGLE_CEMETERY_{idx + 1}_CHANNELER"):
                problems.append((n, f"stop {stop}: his flag shows him on another floor"))
            # His picture, as drawn: patched before the stage dispatch runs.
            if (h.read8("wSprite04StateData1") == deep.SPRITES["SPRITE_CHANNELER"]) != (stop == chan):
                problems.append((n, f"stop {stop}: his picture disagrees with ordinal {chan}"))
            floor, x, y = t.hideout()
            if floor == NONE:
                problems.append((n, f"stop {stop}: a projection wrote NO_HIDEOUT"))
            elif floor == idx:
                here_hide.append(stop)
            if (x, y) != (NONE, NONE) and cell_at is None:
                cell_at = stop
            now = used()
            if now & before != before or bin(now & ~before).count("1") > 1:
                problems.append((n, f"stop {stop}: prefab mask {before:04x} -> {now:04x}"))
            before = now
            if want[0] in (2, 3):
                maps[want] = t.floor_map(want[0])
                bit = 1 << (want[0] - 1)
                empty = want[1] and shadow == (deep.GOT_2B if want[0] == 2 else deep.GOT_3B)
                if bool(t.item_got() & bit) != empty:
                    problems.append((n, f"stop {stop}: its ball disagrees with the coin {shadow:02x}"))
        else:
            if here_chan != [chan]:
                problems.append((n, f"Channeler ordinal {chan} stood at stops {here_chan}"))
            if here_hide != [hide]:
                problems.append((n, f"hideout ordinal {hide} stood at stops {here_hide}"))
            if cell_at != hide:
                problems.append((n, f"hideout ordinal {hide}: its cell was picked at stop {cell_at}"))
            if maps[(2, True)] == maps[(2, False)] or maps[(3, True)] == maps[(3, False)]:
                problems.append((n, "a b floor is its a floor's map"))
finally:
    h.close()

print(f"cemeteries {args.cemeteries}, Channeler ordinals {dict(sorted(seen_ordinals.items()))}")
for p in problems[:20]:
    print("PROBLEM", p)
both = ball_split.get(0, 0)
print(f"b floors' balls: both {both}, 2b none {ball_split.get(deep.GOT_2B, 0)}, "
      f"3b none {ball_split.get(deep.GOT_3B, 0)}")
if args.cemeteries >= 60 and not 0.35 <= both / args.cemeteries <= 0.65:
    problems.append(("rate", f"both b floors kept a ball in {both} of {args.cemeteries}"))
missing = [o for o in range(6) if o not in seen_ordinals] if args.cemeteries >= 60 else []
if missing:
    print("PROBLEM Channeler ordinals never rolled:", missing)
ok = not problems and not missing
print("AUDIT", "OK" if ok else "FAILED", f"({len(problems)} problems)")
sys.exit(0 if ok else 1)
