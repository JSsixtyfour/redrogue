#!/usr/bin/env python3
"""Emit the Facility per-block walkable-quadrant table (PROCEDURAL_SUBROOMS_PLAN Phase 2).

One byte per block in gfx/blocksets/facility.bst: bit 0 = top-left quadrant
walkable, bit 1 = top-right, bit 2 = bottom-left, bit 3 = bottom-right. A
quadrant is walkable when its collision tile (block tile offsets 5, 7, 13, 15,
the same ones audit_facility_stranded_quadrants.py uses) is in Facility_Coll.

Derived, never hand-edited: PFacPlacePads trusts it to prove a pad cannot strand
anything, so a stale table is a softlock risk. FacilityQuadMaskFreshnessTest
fails when it is out of date.

Usage (from the repo root):
    python3 tools/gen_facility_quad_masks.py           # rewrite the table
    python3 tools/gen_facility_quad_masks.py --check   # exit 1 if stale
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BLOCKSET = ROOT / "gfx" / "blocksets" / "facility.bst"
COLLISION = ROOT / "data" / "tilesets" / "collision_tile_ids.asm"
OUT = ROOT / "data" / "tilesets" / "facility_quad_masks.asm"
QUADRANT_TILE_INDEXES = (5, 7, 13, 15)


def walkable_tiles() -> set[int]:
    text = COLLISION.read_text(encoding="utf-8")
    match = re.search(r"^Facility_Coll::\s*\n\s*coll_tiles\s+([^\n;]+)", text, re.M)
    if not match:
        raise SystemExit("Facility_Coll not found in collision_tile_ids.asm")
    return {int(tok.strip().lstrip("$"), 16) for tok in match.group(1).split(",")}


def render() -> str:
    walkable = walkable_tiles()
    blocks = BLOCKSET.read_bytes()
    if len(blocks) % 16:
        raise SystemExit("facility.bst is not a whole number of 16-byte blocks")
    lines = [
        "; GENERATED by tools/gen_facility_quad_masks.py from facility.bst and",
        "; Facility_Coll. Do not edit by hand; rerun the tool.",
        "; One byte per block: bit 0 TL, 1 TR, 2 BL, 3 BR = that quadrant is walkable.",
        "FacilityQuadWalkMasks:",
    ]
    count = len(blocks) // 16
    for start in range(0, count, 8):
        row = []
        for block in range(start, min(start + 8, count)):
            mask = 0
            for bit, index in enumerate(QUADRANT_TILE_INDEXES):
                if blocks[block * 16 + index] in walkable:
                    mask |= 1 << bit
            row.append(f"%{mask:04b}")
        lines.append(f"\tdb {', '.join(row)} ; ${start:02X}")
    lines.append(f"DEF NUM_FACILITY_QUAD_MASKS EQU {count}")
    return "\n".join(lines) + "\n"


def main() -> int:
    text = render()
    if "--check" in sys.argv[1:]:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(f"{OUT.relative_to(ROOT)} is stale: run tools/gen_facility_quad_masks.py")
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
