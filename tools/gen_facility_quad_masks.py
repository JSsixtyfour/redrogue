#!/usr/bin/env python3
"""Emit the per-block walkable-quadrant tables for the Facility (PROCEDURAL_SUBROOMS_PLAN
Phase 2) and the Cemetery.

One byte per block in the tileset's blockset: bit 0 = top-left quadrant
walkable, bit 1 = top-right, bit 2 = bottom-left, bit 3 = bottom-right. A
quadrant is walkable when its collision tile (block tile offsets 4, 6, 12, 14:
the quadrant's bottom-LEFT tile, the one the engine tests; measured 2026-10-14,
FOLLOWUPS #69) is in the tileset's collision list.

Derived, never hand-edited: PFacPlacePads and the two hideout rules
(PFacHideoutKeepsWayOpen, PCemHideoutKeepsWayOpen) trust them to prove nothing is
stranded, so a stale table is a softlock risk. FacilityQuadMaskFreshnessTest
fails when one is out of date.

Usage (from the repo root):
    python3 tools/gen_facility_quad_masks.py           # rewrite the tables
    python3 tools/gen_facility_quad_masks.py --check   # exit 1 if stale
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
COLLISION = ROOT / "data" / "tilesets" / "collision_tile_ids.asm"
QUADRANT_TILE_INDEXES = (4, 6, 12, 14)  # bottom-LEFT tile, measured 2026-10-14 (FOLLOWUPS #69)
TABLES = (  # blockset, collision label, output, table label, count constant
    ("facility.bst", "Facility_Coll", "facility_quad_masks.asm", "FacilityQuadWalkMasks", "NUM_FACILITY_QUAD_MASKS"),
    ("cemetery.bst", "Cemetery_Coll", "cemetery_quad_masks.asm", "CemeteryQuadWalkMasks", "NUM_CEMETERY_QUAD_MASKS"),
)


def walkable_tiles(label: str) -> set[int]:
    text = COLLISION.read_text(encoding="utf-8")
    match = re.search(rf"^{label}::\s*\n\s*coll_tiles\s+([^\n;]+)", text, re.M)
    if not match:
        raise SystemExit(f"{label} not found in collision_tile_ids.asm")
    return {int(tok.strip().lstrip("$"), 16) for tok in match.group(1).split(",")}


def render(blockset: str, collision: str, table: str, constant: str) -> str:
    walkable = walkable_tiles(collision)
    blocks = (ROOT / "gfx" / "blocksets" / blockset).read_bytes()
    if len(blocks) % 16:
        raise SystemExit(f"{blockset} is not a whole number of 16-byte blocks")
    lines = [
        f"; GENERATED by tools/gen_facility_quad_masks.py from {blockset} and",
        f"; {collision}. Do not edit by hand; rerun the tool.",
        "; One byte per block: bit 0 TL, 1 TR, 2 BL, 3 BR = that quadrant is walkable.",
        f"{table}:",
    ]
    count = len(blocks) // 16
    for start in range(0, count, 8):
        row = []
        for block in range(start, min(start + 8, count)):
            mask = 0
            for bit, index in enumerate(QUADRANT_TILE_INDEXES):
                if blocks[block * 16 + index] in walkable:
                    mask |= 1 << bit
            row.append(f"%{mask:04b}")
        lines.append(f"\tdb {', '.join(row)} ; ${start:02X}")
    lines.append(f"DEF {constant} EQU {count}")
    return "\n".join(lines) + "\n"


def main() -> int:
    stale = 0
    for blockset, collision, output, table, constant in TABLES:
        out = ROOT / "data" / "tilesets" / output
        text = render(blockset, collision, table, constant)
        if "--check" in sys.argv[1:]:
            current = out.read_text(encoding="utf-8") if out.exists() else ""
            if current != text:
                print(f"{out.relative_to(ROOT)} is stale: run tools/gen_facility_quad_masks.py")
                stale = 1
            continue
        out.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {out.relative_to(ROOT)}")
    return stale


if __name__ == "__main__":
    raise SystemExit(main())
