#!/usr/bin/env python3
"""Generate data/pokemon/dex_display_rows.asm: the Pokedex list's row order.

Split by kind (2026-11-03):
  - every species row in Pokedex-number order (1..NUM_POKEMON);
  - each REGIONAL form identity directly after its base species, unnumbered;
  - the DISTINCT species stored as forms (DISTINCT below) at the end, numbered
    NUM_POKEMON + 1 onward in DEX_FORM_* id order.

    python3 tools/gen_dex_display_rows.py          # rewrite the file
    python3 tools/gen_dex_display_rows.py --check  # exit 1 if it is stale
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
OUT = REPO / "data" / "pokemon" / "dex_display_rows.asm"

# Identities that are species in their own right, not variants of the base.
DISTINCT = {
    "DEX_FORM_SCREAM_TAIL", "DEX_FORM_WIGLETT", "DEX_FORM_WUGTRIO", "DEX_FORM_PERRSERKER",
    "DEX_FORM_TOEDSCOOL", "DEX_FORM_TOEDSCRUEL", "DEX_FORM_SANDY_SHOCKS", "DEX_FORM_GLACEON",
    "DEX_FORM_SYLVEON", "DEX_FORM_ESPEON", "DEX_FORM_UMBREON", "DEX_FORM_LEAFEON",
    "DEX_FORM_CLODSIRE", "DEX_FORM_HONCHKROW", "DEX_FORM_URSALUNA",
}


def dex_species_order() -> list[str]:
    text = (REPO / "constants" / "pokedex_constants.asm").read_text(encoding="utf-8")
    text = text[:text.index("DEF NUM_POKEMON")]
    return re.findall(r"^\s*const\s+(DEX_\w+)", text, re.M)


def render() -> str:
    species = dex_species_order()
    catalog = re.findall(r"^\s*dex_form\s+(DEX_FORM_\w+),\s*(\w+),\s*\d",
                         (REPO / "data" / "pokemon" / "dex_forms.asm").read_text(encoding="utf-8"), re.M)
    unknown = DISTINCT - {name for name, _ in catalog}
    assert not unknown, unknown
    regional: dict[str, list[str]] = {}
    for name, base in catalog:
        if name not in DISTINCT:
            assert "DEX_" + base in species, f"{name}: no DEX_{base}"
            regional.setdefault("DEX_" + base, []).append(name)
    lines = [
        "; GENERATED by tools/gen_dex_display_rows.py - do not edit by hand.",
        "; The Pokedex list's rows (custom_functions/dex_list.asm). dw per row:",
        ";   DEX_ROW_SPECIES | dex number    a species, numbered as today",
        ";   DEX_ROW_REGIONAL | DEX_FORM_*   a regional form, unnumbered, after its base",
        ";   DEX_ROW_NUMBERED | DEX_FORM_*   a distinct species, numbered from NUM_POKEMON + 1",
        "",
        "DexDisplayRows::",
    ]
    for dex in species:
        lines.append(f"\tdw DEX_ROW_SPECIES | {dex}")
        for name in regional.get(dex, []):
            lines.append(f"\tdw DEX_ROW_REGIONAL | {name}")
    lines.append("DexDisplayRowsNumbered::")
    for name, _ in catalog:
        if name in DISTINCT:
            lines.append(f"\tdw DEX_ROW_NUMBERED | {name}")
    lines += [
        "DexDisplayRowsEnd::",
        "\tASSERT (DexDisplayRowsEnd - DexDisplayRows) / 2 == NUM_DEX_IDENTITIES, \\",
        "\t       \"every identity needs exactly one Pokedex row\"",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(f"{OUT.relative_to(REPO)} is stale: run tools/gen_dex_display_rows.py")
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
