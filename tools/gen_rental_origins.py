#!/usr/bin/env python3
"""Derive Stadium-only origin eligibility from the existing curated corpus."""
import argparse
from pathlib import Path
import gen_movesets as corpus

OUT = Path(corpus.ROOT) / "data/trainers/rental_origins.asm"
CREATOR = "Official Pokémon Stadium rental set — individual designer unknown"


def render(source):
    built = corpus.build(source)
    # Origin IDs are shared with the already assembled corpus. Never emit a
    # filter against a different corpus or roster revision.
    if Path(corpus.OUT).read_text(encoding="utf-8") != corpus.render(*built):
        raise ValueError("regenerate movesets.asm before deriving rental origins")
    origins = built[2]
    official, other = set(), set()
    for record in corpus.parse_records(source):
        label = corpus.display_text(corpus.loss_label(record))
        (official if record.get("Set Creator") == CREATOR else other).add(label)
    if official & other:
        raise ValueError("rental and non-rental records share displayed origin IDs")
    ids = {i for i, label in enumerate(origins) if label in official}
    if not ids:
        raise ValueError("no official Stadium rental origins found")
    bitmap = [sum(1 << bit for bit in range(8) if byte * 8 + bit in ids)
              for byte in range(32)]
    return ("; Generated by tools/gen_rental_origins.py from Set Creator metadata.\n"
            "; IDs match the existing MovesetSpeciesIndex corpus, not name keywords.\n"
            "; Bit i marks origin i as an official Pokemon Stadium rental set.\n"
            "RentalStadiumOrigins:\n" +
            "".join("\tdb " + ", ".join(f"${b:02x}" for b in bitmap[n:n+8]) + "\n"
                    for n in range(0, 32, 8)))


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--source", default=corpus.DEFAULT_SOURCE)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    output = render(args.source)
    if args.check:
        if OUT.read_text(encoding="utf-8") != output:
            raise SystemExit("rental_origins.asm is stale")
        print("rental origins up to date")
    else:
        OUT.write_text(output, encoding="utf-8", newline="\n")
        print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
